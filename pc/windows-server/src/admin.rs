/// 相册缩略图（PC 侧按需生成 + 内存缓存目录 `%TEMP%\vrc-thumbs`）
/// 200 格相册如果逐个拉原图会直接打爆 adb；这里返回 360px JPEG
pub async fn api_fileman_thumb(
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    Query(q): Query<FilemanPathQuery>,
) -> Result<Response, (StatusCode, Json<serde_json::Value>)> {
    if !is_loopback(&peer) {
        return Err((StatusCode::FORBIDDEN, Json(json!({ "error": "forbidden" }))));
    }
    let path = q.path.unwrap_or_default();
    match run_blocking(move || crate::fileman::thumb(&path)).await {
        Ok(bytes) => {
            let mut builder = Response::builder()
                .status(StatusCode::OK)
                .header(header::CONTENT_TYPE, "image/jpeg")
                .header(header::CACHE_CONTROL, "private, max-age=86400")
                .header("X-Content-Type-Options", "nosniff");
            builder = builder.header(header::CONTENT_LENGTH, bytes.len().to_string());
            let body = builder.body(Body::from(bytes)).map_err(|e| anyhow_bad_gateway(anyhow::anyhow!("{e}")))?;
            Ok(body)
        }
        Err(e) => Err((StatusCode::NOT_FOUND, Json(json!({ "error": format!("{e:#}") })))),
    }
}

/// 上传：body 原始字节流（路由层已关闭 body 大小限制），先落临时文件再 adb push
pub async fn api_fileman_upload(
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    Query(q): Query<FilemanPathQuery>,
    body: Body,
) -> Result<Json<serde_json::Value>, (StatusCode, Json<serde_json::Value>)> {
    if !is_loopback(&peer) {
        return Err((StatusCode::FORBIDDEN, Json(json!({ "error": "forbidden" }))));
    }
    use futures::StreamExt;
    use tokio::io::AsyncWriteExt;
    let dest = match crate::fileman::normalize_path(&q.path.clone().unwrap_or_default()) {
        Ok(p) => p,
        Err(e) => return Err((StatusCode::BAD_REQUEST, Json(json!({ "error": format!("{e:#}") })))),
    };
    if dest == "/sdcard" {
        return Err((StatusCode::BAD_REQUEST, Json(json!({ "error": "上传目标必须是文件路径" }))));
    }
    let tmp = std::env::temp_dir().join(format!("vrc-upload-{}-{}.tmp", std::process::id(), rand::random::<u64>()));
    let write_result: anyhow::Result<u64> = async {
        let mut file = tokio::fs::File::create(&tmp).await?;
        let mut stream = body.into_data_stream();
        let mut total: u64 = 0;
        while let Some(chunk) = stream.next().await {
            let bytes = chunk.map_err(|e| anyhow::anyhow!("读取请求体失败: {e}"))?;
            file.write_all(&bytes).await?;
            total += bytes.len() as u64;
        }
        file.flush().await?;
        Ok(total)
    }
    .await;
    let size = match write_result {
        Ok(n) => n,
        Err(e) => {
            let _ = std::fs::remove_file(&tmp);
            return Err(anyhow_bad_gateway(e));
        }
    };
    let tmp2 = tmp.clone();
    let dest2 = dest.clone();
    let push = run_blocking(move || crate::fileman::adb_push(&tmp2, &dest2)).await;
    let _ = std::fs::remove_file(&tmp);
    match push {
        Ok(()) => Ok(Json(json!({ "ok": true, "path": dest, "size": size }))),
        Err(e) => Err(anyhow_bad_gateway(e)),
    }
}
