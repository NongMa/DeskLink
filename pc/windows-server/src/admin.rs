fn fileman_stream_response(
    path: &str,
    inline: bool,
) -> anyhow::Result<Response> {
    let norm = crate::fileman::normalize_path(path)?;
    let script = crate::fileman::cat_script(&norm)?;
    let len = crate::fileman::file_size(&norm);
    let mut cmd = crate::fileman::exec_out_command(&script)?;
    let mut child = cmd.spawn()?;
    let stdout = child.stdout.take().ok_or_else(|| anyhow::anyhow!("无法取得子进程 stdout"))?;
    let stream = futures::stream::unfold((child, stdout), |(mut child, mut out)| async move {
        use tokio::io::AsyncReadExt;
        let mut buf = vec![0u8; 64 * 1024];
        match out.read(&mut buf).await {
            Ok(0) => {
                let _ = child.wait().await;
                None
            }
            Ok(n) => Some((Ok::<Vec<u8>, std::io::Error>(buf[..n].to_vec()), (child, out))),
            Err(e) => Some((Err(e), (child, out))),
        }
    });
    let mut builder = Response::builder()
        .status(StatusCode::OK)
        .header(header::CONTENT_TYPE, crate::fileman::mime_of(&norm))
        .header(header::CONTENT_DISPOSITION, crate::fileman::content_disposition(&norm, inline))
        .header("X-Content-Type-Options", "nosniff");
    if let Some(n) = len {
        builder = builder.header(header::CONTENT_LENGTH, n.to_string());
    }
    Ok(builder.body(Body::from_stream(stream))?)
}

