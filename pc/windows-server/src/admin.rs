fn pair_payload(st: &AppState) -> serde_json::Value {
    let link = st.pair_link();
    json!({
        "link": link,
        "qr_svg": qr_svg(&link),
        "token": st.token(),
        "device_name": st.device_name(),
    })
}

fn qr_svg(content: &str) -> String {
    use qrcode::types::QrError;
    use qrcode::QrCode;
    let code = match QrCode::new(content.as_bytes()) {
        Ok(c) => c,
        Err(QrError::DataTooLong) => return String::new(),
        Err(_) => return String::new(),
    };
    let colors = code.to_colors();
    let w = code.width();
    let quiet = 2usize;
    let scale = 6usize;
    let size = (w + quiet * 2) * scale;
    let mut out = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 {size} {size}\" shape-rendering=\"crispEdges\"><rect width=\"{size}\" height=\"{size}\" fill=\"#ffffff\"/>"
    );
    for y in 0..w {
        for x in 0..w {
            if colors[y * w + x] == qrcode::Color::Dark {
                let px = (x + quiet) * scale;
                let py = (y + quiet) * scale;
                out.push_str(&format!(
                    "<rect x=\"{px}\" y=\"{py}\" width=\"{scale}\" height=\"{scale}\" fill=\"#0b1526\"/>"
                ));
            }
        }
    }
    out.push_str("</svg>");
    out
}

