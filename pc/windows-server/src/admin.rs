pub async fn api_settings_post(
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    State(st): State<Arc<AppState>>,
    Json(update): Json<SettingsUpdate>,
) -> Result<Json<serde_json::Value>, StatusCode> {
    if !is_loopback(&peer) {
        return Err(StatusCode::FORBIDDEN);
    }
    if let Some(v) = update.auth_required {
        st.set_auth_required(v);
        st.persist();
        log::info!("admin set auth_required = {v}");
    }
    if let Some(n) = update.device_name {
        let n = n.trim().to_string();
        if !n.is_empty() && n != st.device_name() {
            st.set_device_name(n.clone());
            st.persist();
            log::info!("admin set device_name = {n}");
        }
    }
    if let Some(v) = update.autostart {
        match crate::autostart::set_enabled(v) {
            Ok(()) => log::info!("admin set autostart = {v}"),
            Err(e) => log::error!("failed to set autostart: {e:#}"),
        }
    }
    Ok(Json(json!({
        "auth_required": st.auth_required(),
        "autostart": crate::autostart::is_enabled(),
        "device_name": st.device_name(),
    })))
}

