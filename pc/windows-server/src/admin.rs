/// 面板按钮 → adb keyevent。key 取值：BACK/HOME/RECENTS/VOLUME_UP/VOLUME_DOWN/POWER/NOTIFICATION/SCREENSHOT
pub async fn api_mirror_key(
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    Json(body): Json<MirrorKey>,
) -> Result<Json<serde_json::Value>, (StatusCode, Json<serde_json::Value>)> {
    if !is_loopback(&peer) {
        return Err((
            StatusCode::FORBIDDEN,
            Json(json!({ "error": "forbidden" })),
        ));
    }
    let code: u32 = match body.key.as_str() {
        "BACK" => 4,
        "HOME" => 3,
        "RECENTS" => 187,
        "VOLUME_UP" => 24,
        "VOLUME_DOWN" => 25,
        "POWER" => 26,
        "NOTIFICATION" => 83,
        "SCREENSHOT" => 313,
        _ => {
            return Err((
                StatusCode::BAD_REQUEST,
                Json(json!({ "error": format!("unknown key: {}", body.key) })),
            ))
        }
    };
    match crate::mirror::send_keyevent(code) {
        Ok(()) => Ok(Json(json!({ "ok": true }))),
        Err(e) => {
            log::error!("admin mirror key {} failed: {e:#}", body.key);
            Err((
                StatusCode::BAD_GATEWAY,
                Json(json!({ "error": format!("{e:#}") })),
            ))
        }
    }
}

