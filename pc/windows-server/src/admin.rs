use axum::response::Response;

fn anyhow_bad_gateway(e: anyhow::Error) -> (StatusCode, Json<serde_json::Value>) {
    (StatusCode::BAD_GATEWAY, Json(json!({ "error": format!("{e:#}") })))
}

async fn run_blocking<T: Send + 'static>(f: impl FnOnce() -> anyhow::Result<T> + Send + 'static) -> anyhow::Result<T> {
    tokio::task::spawn_blocking(f).await.map_err(|e| anyhow::anyhow!("后台任务失败: {e}"))?
}

